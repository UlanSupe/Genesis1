def parse_junit(path: str | Path) -> dict:
    """{ 'test_file.py::test_name': [passed?, ...] } from a pytest --junitxml file."""
    res: dict = {}
    for tc in ET.parse(path).getroot().iter("testcase"):
        mod = tc.get("classname", "").split(".")[-1] + ".py"
        name = tc.get("name", "").split("[")[0]
        ok = not any(c.tag in ("failure", "error") for c in tc)
        skipped = any(c.tag == "skipped" for c in tc)
        res.setdefault(f"{mod}::{name}", []).append(None if skipped else ok)
    return res


def evaluate(results: dict) -> list:
    rows = []
    for req, impl, tests in REQUIREMENTS:
        states, detail = [], []
        for t in tests:
            runs = results.get(t)
            if not runs:
                states.append("UNVERIFIED")
                detail.append(f"{t} (not found)")
            elif any(r is False for r in runs):
                states.append("FAIL")
                detail.append(f"{t} (FAILED)")
            elif any(r is None for r in runs):
                states.append("UNVERIFIED")
                detail.append(f"{t} (skipped)")
            else:
                states.append("PASS")
        status = "FAIL" if "FAIL" in states else ("UNVERIFIED" if "UNVERIFIED" in states else "PASS")
        rows.append({"requirement": req, "implementation": impl, "tests": tests, "status": status,
                     "runs": sum(len(results.get(t, [])) for t in tests), "problems": detail})
    return rows


def render(rows: list, totals: dict | None = None) -> str:
    n = sum(r["status"] == "PASS" for r in rows)
    out = ["# SPEC_COMPLIANCE", "",
           "Generated by `python -m traceforge verify` from a real pytest run. A requirement is **PASS** only if "
           "every test cited for it was found and passed; otherwise it is **FAIL** or **UNVERIFIED**.", "",
           f"Requirements: {len(rows)} | PASS: {n} | FAIL: {sum(r['status'] == 'FAIL' for r in rows)} | "
           f"UNVERIFIED: {sum(r['status'] == 'UNVERIFIED' for r in rows)}"]
    if totals:
        out.append(f"Test run: {totals['passed']} passed, {totals['failed']} failed, {totals['skipped']} skipped "
                   f"({totals['total']} total)")
    out += ["", "| # | Requirement | Implementation | Test (cited, executions) | Status |", "|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        tests = "<br>".join(t.replace("::", " :: ") for t in r["tests"])
        out.append(f"| {i} | {r['requirement']} | `{r['implementation']}` | {tests}<br>({r['runs']} executions) | **{r['status']}** |")
    problems = [(r["requirement"], p) for r in rows for p in r["problems"]]
    if problems:
        out += ["", "## Problems", ""] + [f"* {a}: {b}" for a, b in problems]
    return "\n".join(out) + "\n"
